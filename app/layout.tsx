import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import Link from "next/link";
import "./globals.css";
import { prisma } from "@/src/lib/prisma";
import { getActiveUser } from "@/src/lib/session";
import { logout } from "@/src/actions/auth";
import { ROLE_LABELS, isAgentRole } from "@/src/types/itil";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

const NAV_LINK_CLASS =
  "text-sm text-zinc-600 hover:text-black dark:text-zinc-400 dark:hover:text-zinc-50";

// This layout is now `async` — layouts and pages are allowed to be async
// functions in the App Router, and `await`-ing here is what lets us read
// the request's session cookie before the HTML is built, on every
// request (the root page below already opted the app into dynamic
// rendering, which is what makes "every request" true here too).
export default async function RootLayout({ children }: LayoutProps<"/">) {
  const activeUser = await getActiveUser();
  const unreadCount = activeUser
    ? await prisma.notification.count({ where: { recipientId: activeUser.id, read: false } })
    : 0;

  // Rendered twice below (once as the horizontal desktop row, once
  // stacked in the mobile dropdown), so the link list lives here once
  // rather than being written out twice and risking the two copies
  // drifting apart. The mobile/desktop split itself is plain CSS (a
  // hidden checkbox + peer-checked, see the header markup below), no
  // client JavaScript needed for a menu toggle, same as the rest of this
  // app's forms-over-fetch approach.
  const navLinks = (
    <>
      <Link href="/incidents" className={NAV_LINK_CLASS}>
        Search
      </Link>
      {activeUser && isAgentRole(activeUser.role) && (
        <Link href="/problems" className={NAV_LINK_CLASS}>
          Problems
        </Link>
      )}
      {activeUser && isAgentRole(activeUser.role) && (
        <Link href="/changes" className={NAV_LINK_CLASS}>
          Changes
        </Link>
      )}
      <Link href="/training" className={NAV_LINK_CLASS}>
        Training
      </Link>
      {activeUser && (
        <Link href="/inbox" className={`flex items-center gap-1.5 ${NAV_LINK_CLASS}`}>
          Inbox
          {unreadCount > 0 && (
            <span className="rounded-full bg-red-600 px-1.5 py-0.5 text-xs font-medium text-white">
              {unreadCount}
            </span>
          )}
        </Link>
      )}
    </>
  );

  const accountBlock = activeUser ? (
    <>
      <span className="text-xs text-zinc-500 dark:text-zinc-400">
        {activeUser.name}, {ROLE_LABELS[activeUser.role]}
      </span>
      <form action={logout}>
        <button type="submit" className={NAV_LINK_CLASS}>
          Sign out
        </button>
      </form>
    </>
  ) : (
    <Link
      href="/login"
      className="rounded-full bg-foreground px-4 py-1.5 text-sm font-medium text-background transition-colors hover:bg-[#383838] dark:hover:bg-[#ccc]"
    >
      Sign in
    </Link>
  );

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <header className="border-b border-black/10 dark:border-white/10">
          {/* Hidden checkbox driving the mobile menu, pure CSS (no
              client component / JavaScript needed): the label below
              toggles it, and peer-checked below shows the stacked menu.
              Sits outside both flex rows so it's a shared ancestor's
              child of everything that reacts to it. */}
          <input type="checkbox" id="nav-toggle" className="peer hidden" />

          <div className="flex items-center justify-between px-6 py-3">
            <Link href="/" className="font-semibold text-black dark:text-zinc-50">
              ITIL Service Desk
            </Link>

            {/* Desktop: everything in one row, unchanged from before. */}
            <div className="hidden items-center gap-4 sm:flex">
              {navLinks}
              {accountBlock}
            </div>

            {/* Mobile: a hamburger toggle instead of squeezing every
                link/badge/name into one row, which is what used to wrap
                and overlap on narrow screens. */}
            <label
              htmlFor="nav-toggle"
              aria-label="Toggle menu"
              className="flex cursor-pointer items-center rounded-md border border-black/10 px-3 py-1.5 text-sm text-zinc-600 dark:border-white/10 dark:text-zinc-400 sm:hidden"
            >
              Menu
            </label>
          </div>

          {/* Mobile dropdown, stacked, hidden until the checkbox above is
              checked. */}
          <div className="hidden flex-col gap-3 border-t border-black/10 px-6 py-4 peer-checked:flex dark:border-white/10 sm:hidden">
            {navLinks}
            <div className="flex items-center gap-4 border-t border-black/10 pt-3 dark:border-white/10">
              {accountBlock}
            </div>
          </div>
        </header>
        {children}
      </body>
    </html>
  );
}
